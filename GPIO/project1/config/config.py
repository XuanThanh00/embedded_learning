from machine import mem32

GPIO_BASE = 0x60004000

###OUTPUT REG###
GPIO_ENABLE_REG = GPIO_BASE | 0x0020    # Enable 0-31

GPIO_OUT_REG = GPIO_BASE | 0x0004 		# GPIO 0-31 state

GPIO_OUT_W1TS_REG = GPIO_BASE | 0x0008  # Set 0-31

GPIO_OUT_W1TC_REG = GPIO_BASE | 0x000C  # Clear 0-31

GPIO_ENABLE1_REG = GPIO_BASE | 0x002C	# Enable 32-48

GPIO_OUT1_REG = GPIO_BASE | 0x0010 		# GPIO 32-48 state

GPIO_OUT1_W1TS_REG = GPIO_BASE | 0x0014 # Set 32-48

GPIO_OUT1_W1TC_REG = GPIO_BASE | 0x0018  # Clear 32-48

###INPUT REG###
GPIO_IN_REG = GPIO_BASE | 0x003C  # Read 0-31

GPIO_IN1_REG = GPIO_BASE | 0x0040  # Read 32-48




